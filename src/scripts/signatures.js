/** Weapon name → character, for one game. */
function signatureOf(game, weaponName) {
  return SIGNATURES[game]?.[weaponName];
}

/**
 * Character name → signature weapon. When a character has several (Venti: Elegy for the
 * End, then The Daybreak Chronicles for his later kit), the one listed last wins.
 */
function signatureWeapon(game, characterName) {
  let found;
  for (const [weapon, character] of Object.entries(SIGNATURES[game] || {})) if (character === characterName) found = weapon;
  return found;
}

